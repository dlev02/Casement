            (0x5F, 0x7E), (0x5E, 0x73), (0x5D, 0x7D), (0x68, 0x72), (0x66, 0x71),
            (LeftControl, 0x1D), (LeftShift, 0x2A), (RightShift, 0x36), (LeftOption, 0x38),
        };
        var extended = new (ushort Mac, ushort Scan)[]
        {
            (0x72, 0x52), (0x73, 0x47), (0x74, 0x49), (0x75, 0x53), (0x77, 0x4F), (0x79, 0x51),
            (0x7B, 0x4B), (0x7C, 0x4D), (0x7D, 0x50), (0x7E, 0x48),
            (0x47, 0x45), // Keypad Clear → Num Lock: SendInput wants EXTENDED with 45 (verify on hardware)
            (0x4B, 0x35), (0x4C, 0x1C), (0x6E, 0x5D), (0x4A, 0x20), (0x48, 0x30), (0x49, 0x2E),
            (RightControl, 0x1D), (RightOption, 0x38), (LeftCommand, 0x5B), (RightCommand, 0x5C),
        };
        var table = new Dictionary<ushort, ScanCode>();
        foreach (var (mac, scan) in plain) table.Add(mac, new ScanCode(scan, false));
        foreach (var (mac, scan) in extended) table.Add(mac, new ScanCode(scan, true));
        return table;
    }
}
