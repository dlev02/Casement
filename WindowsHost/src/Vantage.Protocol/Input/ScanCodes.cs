namespace Vantage.Protocol.Input;

/// <summary>A PS/2 set-1 scan code; <see cref="Extended"/> means the E0 prefix (<c>KEYEVENTF_EXTENDEDKEY</c>).</summary>
public readonly record struct ScanCode(ushort Code, bool Extended);

/// <summary>macOS virtual key code (kVK) → Windows set-1 scan code (spec §7.5).</summary>
public static class ScanCodes
{
    public const ushort LeftControl = 0x3B;
    public const ushort RightControl = 0x3E;
    public const ushort LeftShift = 0x38;
    public const ushort RightShift = 0x3C;
    public const ushort LeftOption = 0x3A;
    public const ushort RightOption = 0x3D;
    public const ushort LeftCommand = 0x37;
    public const ushort RightCommand = 0x36;
    public const ushort Function = 0x3F;
    public const ushort Return = 0x24;
    public const ushort Tab = 0x30;

    private static readonly Dictionary<ushort, ScanCode> s_table = Build();

    /// <summary>The scan code for a kVK, or null when it has none on Windows (Fn, unknown codes).</summary>
    public static ScanCode? For(ushort macKeyCode) => s_table.TryGetValue(macKeyCode, out var code) ? code : null;

    /// <summary>Whether the kVK is one of the eight modifier keys (⌃ ⇧ ⌥ ⌘, left and right).</summary>
    public static bool IsModifier(ushort macKeyCode) => macKeyCode is LeftControl or RightControl or LeftShift or RightShift
        or LeftOption or RightOption or LeftCommand or RightCommand;

    private static Dictionary<ushort, ScanCode> Build()
    {
        var plain = new (ushort Mac, ushort Scan)[]
        {
            (0x00, 0x1E), (0x0B, 0x30), (0x08, 0x2E), (0x02, 0x20), (0x0E, 0x12), (0x03, 0x21), (0x05, 0x22), (0x04, 0x23),
            (0x22, 0x17), (0x26, 0x24), (0x28, 0x25), (0x25, 0x26), (0x2E, 0x32), (0x2D, 0x31), (0x1F, 0x18), (0x23, 0x19),
            (0x0C, 0x10), (0x0F, 0x13), (0x01, 0x1F), (0x11, 0x14), (0x20, 0x16), (0x09, 0x2F), (0x0D, 0x11), (0x07, 0x2D),
            (0x10, 0x15), (0x06, 0x2C),
            (0x12, 0x02), (0x13, 0x03), (0x14, 0x04), (0x15, 0x05), (0x17, 0x06), (0x16, 0x07), (0x1A, 0x08), (0x1C, 0x09),
            (0x19, 0x0A), (0x1D, 0x0B),
            (0x24, 0x1C), (0x35, 0x01), (0x33, 0x0E), (0x30, 0x0F), (0x31, 0x39), (0x1B, 0x0C), (0x18, 0x0D), (0x21, 0x1A),
            (0x1E, 0x1B), (0x2A, 0x2B), (0x29, 0x27), (0x27, 0x28), (0x32, 0x29), (0x2B, 0x33), (0x2F, 0x34), (0x2C, 0x35),
            (0x0A, 0x56), (0x39, 0x3A),
            (0x7A, 0x3B), (0x78, 0x3C), (0x63, 0x3D), (0x76, 0x3E), (0x60, 0x3F), (0x61, 0x40), (0x62, 0x41), (0x64, 0x42),
            (0x65, 0x43), (0x6D, 0x44), (0x67, 0x57), (0x6F, 0x58), (0x69, 0x64), (0x6B, 0x65), (0x71, 0x66), (0x6A, 0x67),
            (0x40, 0x68), (0x4F, 0x69), (0x50, 0x6A), (0x5A, 0x6B),
            (0x43, 0x37), (0x4E, 0x4A), (0x45, 0x4E), (0x51, 0x59), (0x41, 0x53), (0x52, 0x52), (0x53, 0x4F), (0x54, 0x50),
