import AppKit
import Foundation
import VantageCore

/// Polls the host pasteboard for changes and applies remote clipboard payloads without looping.
/// Carries plain text, RTF, and images (as PNG).
///
/// Every pasteboard access runs on the main thread: AppKit mutates the pasteboard's owner
/// bookkeeping there, and reading it from another thread is a known crash.
nonisolated final class ClipboardBridge: @unchecked Sendable {
    /// Images larger than this are not synced automatically (bytes of PNG).
    static let maxImageBytes = 24 * 1024 * 1024
    /// How long pasted text stays on the pasteboard before what was there comes back. Apps read
    /// it while handling the ⌘V; one that hasn't by then would paste the old clipboard.
    static let pasteRestoreDelay: TimeInterval = 1.5
    /// nspasteboard.org markers: clipboard managers leave a paste we put there out of history.
    static let pasteMarkers = [NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
                               NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")]

    private let pasteboard: NSPasteboard
    /// Main thread only.
    private var lastChangeCount: Int
    private var timer: DispatchSourceTimer?
    /// Main thread only: what the pasteboard held before `paste`, until it's put back.
    private var heldClipboard: [[(NSPasteboard.PasteboardType, Data)]]?
    private var pastedChangeCount = 0
    private var restoreWork: DispatchWorkItem?
    var onLocalChange: (@Sendable (ClipboardPayload) -> Void)?

    init(pasteboard: NSPasteboard = .general) {
        self.pasteboard = pasteboard
        lastChangeCount = pasteboard.changeCount
    }

    func start() {
        let timer = DispatchSource.makeTimerSource(queue: .main)
        timer.schedule(deadline: .now() + 0.5, repeating: 0.5)
        timer.setEventHandler { [weak self] in self?.poll() }
        timer.resume()
        self.timer = timer
    }

    func stop() {
        timer?.cancel()
        timer = nil
    }

    /// Reads the current pasteboard as a payload (used on session start and on change).
    func currentPayload() -> ClipboardPayload {
        onMain { self.read() }
    }

    /// Sends a change made on this Mac. Changes this bridge wrote itself are already counted.
    func poll() {
        onMain {
            let count = self.pasteboard.changeCount
            guard count != self.lastChangeCount else { return }
            self.lastChangeCount = count
            let payload = self.read()
            if !payload.isEmpty { self.onLocalChange?(payload) }
        }
    }

    /// Applies a payload received from the client and returns once the pasteboard holds it. The
    /// session awaits this before it reads the next message: a Mac client pasting with ⌘V sends
    /// its clipboard and then the ⌘V key on the same stream, and a key posted before a large
    /// clipboard was written pasted the old one. The change count the write leaves behind is
    /// recorded in the same main-thread block, so the next poll never takes it for a local copy
    /// and the one after still sees the user's next real copy.
    func apply(_ payload: ClipboardPayload) async {
        guard !payload.isEmpty else { return }
        await withCheckedContinuation { (done: CheckedContinuation<Void, Never>) in
            DispatchQueue.main.async {
                self.write(payload)
                done.resume()
            }
        }
    }

    /// Pastes `text` into the focused app: puts it on the pasteboard, runs `pressPaste` (a ⌘V),
    /// and puts back what was there `pasteRestoreDelay` later. Typing long text drops keys in
    /// Chromium and Electron apps; a paste arrives whole. Neither write is sent to the client,
    /// pastes in a row keep the original clipboard, and a copy made in between wins.
    func paste(_ text: String, pressPaste: @escaping @Sendable () -> Void) async {
        await withCheckedContinuation { (done: CheckedContinuation<Void, Never>) in
            DispatchQueue.main.async {
                self.restoreWork?.cancel()
                if self.heldClipboard == nil { self.heldClipboard = self.snapshot() }
                let item = NSPasteboardItem()
                item.setString(text, forType: .string)
                for marker in Self.pasteMarkers { item.setString("", forType: marker) }
                // This Mac only: a dictation shouldn't reach other devices through Universal Clipboard.
                self.pasteboard.prepareForNewContents(with: .currentHostOnly)
                self.pasteboard.writeObjects([item])
                self.lastChangeCount = self.pasteboard.changeCount
                self.pastedChangeCount = self.lastChangeCount
                pressPaste()
                // Holds the bridge until it runs, so a session that ends first still restores.
                let work = DispatchWorkItem { self.restoreHeldClipboard() }
                self.restoreWork = work
                DispatchQueue.main.asyncAfter(deadline: .now() + Self.pasteRestoreDelay, execute: work)
                done.resume()
            }
        }
    }

    /// Main thread.
    private func restoreHeldClipboard() {
        restoreWork = nil
        guard let held = heldClipboard else { return }
        heldClipboard = nil
        guard pasteboard.changeCount == pastedChangeCount else { return }
        pasteboard.clearContents()
        let items = held.map { types in
            let item = NSPasteboardItem()
            for (type, data) in types { item.setData(data, forType: type) }
            return item
        }
        if !items.isEmpty { pasteboard.writeObjects(items) }
        lastChangeCount = pasteboard.changeCount
    }

    /// Main thread: every item's every type, so a restore gives back exactly what was copied.
    private func snapshot() -> [[(NSPasteboard.PasteboardType, Data)]] {
        (pasteboard.pasteboardItems ?? []).map { item in
            item.types.compactMap { type in item.data(forType: type).map { (type, $0) } }
        }
    }

    /// Main thread.
    func write(_ payload: ClipboardPayload) {
        pasteboard.clearContents()
        var types: [NSPasteboard.PasteboardType] = []
        if payload.text != nil { types.append(.string) }
        if payload.rtf != nil { types.append(.rtf) }
        if payload.imagePNG != nil { types.append(.png); types.append(.tiff) }
        pasteboard.declareTypes(types, owner: nil)
        if let text = payload.text { pasteboard.setString(text, forType: .string) }
        if let rtf = payload.rtf { pasteboard.setData(rtf, forType: .rtf) }
        if let png = payload.imagePNG {
            pasteboard.setData(png, forType: .png)
            if let image = NSImage(data: png), let tiff = image.tiffRepresentation {
                pasteboard.setData(tiff, forType: .tiff)
            }
        }
        lastChangeCount = pasteboard.changeCount
    }

    private func read() -> ClipboardPayload {
        var payload = ClipboardPayload()
        payload.text = pasteboard.string(forType: .string)
        payload.rtf = pasteboard.data(forType: .rtf)
        if let png = pasteboard.data(forType: .png), png.count <= Self.maxImageBytes {
            payload.imagePNG = png
        } else if let tiff = pasteboard.data(forType: .tiff),
                  let rep = NSBitmapImageRep(data: tiff),
                  let png = rep.representation(using: .png, properties: [:]),
                  png.count <= Self.maxImageBytes {
            payload.imagePNG = png
        }
        return payload
    }

    /// Runs on the main thread, synchronously. The session actor calls in from the cooperative
    /// pool; the main thread never blocks on the session, so the hop can't deadlock.
    private func onMain<T>(_ body: () -> T) -> T {
        if Thread.isMainThread { return body() }
        return DispatchQueue.main.sync(execute: body)
    }
}
